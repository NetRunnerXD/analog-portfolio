"""Python/JS parity fixture (review-01).

Generates pipeline/tests/fixtures/parity_cases.json (edge-case inputs + Python reference outputs) and a tiny
grid binary pipeline/tests/fixtures/parity_grid.{json,bin} with NaNs, clipping and odd-length uint8 columns.
pytest checks the fixture is current (tests/test_parity_fixture.py); vitest runs the same cases through the
JS port (web/src/scoring/parity.test.ts). Regenerate after changing the scalar scorer:

    python tests/make_parity_fixture.py
"""
from __future__ import annotations

import json
import math
import random
from pathlib import Path

import numpy as np

from analog_portfolio.grid import cell_id
from analog_portfolio.grid.binary import read_grid, write_grid
from analog_portfolio.score import (bounded_fraction, flag_match, gaussian, geometric_mean, ordinal_class,
                                    ratio_sim, total_score)
from analog_portfolio.score.setcover import greedy_portfolio

FIXTURES = Path(__file__).parent / "fixtures"
GRID_STEM = FIXTURES / "parity_grid"


def build_cases() -> dict:
    rnd = random.Random(20261114)
    c: dict = {"note": "Generated by pipeline/tests/make_parity_fixture.py; do not edit by hand.", "tolerance": 1e-12}
    xs = [0, 1e-9, 0.5, 1, 6.36, 17, 100, 214, 288, 320, 500, 1e6]
    c["ratio_sim"] = [dict(x=x, t=t, expected=ratio_sim(x, t)) for x in xs for t in xs]
    fr = [-0.5, 0, 0.004, 0.3, 0.35, 0.5, 0.996, 1, 1.5]
    c["bounded_fraction"] = [dict(x=x, t=t, expected=bounded_fraction(x, t)) for x in fr for t in fr]
    c["gaussian"] = [dict(x=x, t=t, tau=tau, expected=gaussian(x, t, tau))
                     for x in [-30, -5, 0, 0.55, 5, 10, 90, 1000] for t in [0, 0.55, 50] for tau in [0.5, 3, 5]]
    c["ordinal_class"] = [dict(x=x, t=t, n_classes=n, expected=ordinal_class(x, t, n))
                          for n in (3, 5) for x in range(1, n + 1) for t in range(1, n + 1)]
    c["flag_match"] = [dict(earth=e, target=t, expected=flag_match(e, t))
                       for e in range(128) for t in (0, 1, 17, 33, 49, 64, 127)]
    gm = []
    for i in range(60):
        k = rnd.randint(1, 10)
        fs = [f"F{j}" for j in range(1, k + 1)]
        scores = {f: rnd.choice([0.0, 0.0, 0.005, 0.01, 0.2, 0.5, 0.7, 1.0, round(rnd.random(), 6)]) for f in fs}
        weights = {f: rnd.choice([0, 0, 5, 10, 15, 25, 30]) for f in fs}
        if i % 15 == 0:
            weights = {f: 0 for f in fs}  # no active weights -> 0
        floor = rnd.choice([0.01, 0.01, 0.001, 0.1])
        gm.append(dict(scores=scores, weights=weights, floor=floor, expected=geometric_mean(scores, weights, floor)))
    c["geometric_mean"] = gm
    c["total_score"] = [dict(core=core, secondary=sec, expected=total_score(core, sec))
                        for core in (0, 0.01, 0.5, 1) for sec in ([], [0], [0.1, 0.0, 0.5], [0.1, 0.006, 1], [1, 1, 1])]
    lats = [90, 89.9, 89.75, 89.5, 45.25, 0.25, 0.0, -0.0, -0.25, -45, -89.5, -89.75, -89.9, -90]
    lons = [-540, -360, -180, -179.999, -179.75, -0.5, 0, 0.25, 179.5, 179.75, 179.99999999999997, 180, 203.35, 360,
            540]
    c["cell_id"] = [dict(lat=la, lon=lo, expected=cell_id(la, lo)) for la in lats for lo in lons]
    sc = []
    for i in range(80):
        nf = rnd.randint(2, 8)
        fs = [f"F{j}" for j in range(1, nf + 1)]
        weights = {f: rnd.choice([0, 5, 10, 10, 20, 30]) for f in fs}
        sites = []
        for j in range(rnd.randint(1, 12)):
            sites.append(dict(site_id=f"s{j}", cost=rnd.choice([0.0, 0.1, 0.5, 0.5, 1.0]),
                              factor_scores={f: rnd.choice([0.0, 0.5, 0.69, 0.7, 0.7, 0.75, 0.9, 1.0]) for f in fs}))
        if i % 10 == 0 and sites:  # exact duplicate candidate (same scores) under another id
            sites.append(dict(sites[0], site_id=f"dup_of_{sites[0]['site_id']}"))
        theta = rnd.choice([0.7, 0.7, 0.5, 0.9])
        lam = rnd.choice([0.0, 0.5, 2.0, 20.0])
        max_sites = rnd.choice([1, 3, 5])
        chosen, covered, unc = greedy_portfolio(sites, weights, theta, lam, max_sites)
        sc.append(dict(sites=sites, weights=weights, theta=theta, lam=lam, max_sites=max_sites,
                       expected_ids=[s["site_id"] for s in chosen], expected_covered=sorted(covered),
                       expected_uncoverable=sorted(unc)))
    c["set_cover"] = sc
    c["grid"] = {"manifest": GRID_STEM.name + ".json", "expected": None}
    return c


GRID_COLUMNS = [
    # odd lengths/types exercise 4-byte alignment padding; NaN -> nodata; out-of-range -> clipped
    dict(name="cell_id", factor=None, dtype="uint32", scale=1, add_offset=0,
         values=[0, 1, 720, 129240, 257845, 259198, 259199]),
    dict(name="ts_mean_k", factor="F1", dtype="uint16", scale=0.01, add_offset=150,
         values=[150.0, 213.37, math.nan, 300.004, 805.33, 100.0, 1000.0]),
    dict(name="ti_class", factor="F3", dtype="uint8", scale=1, add_offset=0, values=[1, 2, 3, 4, 5, math.nan, 0]),
    dict(name="barren_frac", factor="F8", dtype="uint8", scale=0.004, add_offset=0,
         values=[0.0, 0.002, 0.5, 1.0, 1.02, math.nan, 0.996]),
    dict(name="noon_sun_elev_deg", factor="F10", dtype="uint8", scale=0.5, add_offset=-30,
         values=[-30.0, -0.26, 0.55, 89.75, 96.5, math.nan, 200.0]),
    dict(name="elevation_m", factor=None, dtype="uint16", scale=1, add_offset=-500,
         values=[-430.0, 0.0, 8848.0, math.nan, -1000.0, 65034.0, 70000.0]),
]


def write_grid_fixture() -> None:
    write_grid(GRID_STEM, "earth", "sparse", [dict(c, units="", values=np.array(c["values"], dtype="float64"))
                                              for c in GRID_COLUMNS], mock=True)
    m = json.loads(GRID_STEM.with_suffix(".json").read_text())
    m["generated_at"] = "fixture"  # keep the fixture byte-stable across regenerations
    GRID_STEM.with_suffix(".json").write_text(json.dumps(m, indent=1) + "\n")


def decoded_grid() -> dict:
    g = read_grid(GRID_STEM.with_suffix(".json"))
    return {k: [None if (isinstance(v, float) and math.isnan(v)) else v for v in np.asarray(a).tolist()]
            for k, a in g.items()}


def main() -> None:
    FIXTURES.mkdir(parents=True, exist_ok=True)
    write_grid_fixture()
    cases = build_cases()
    cases["grid"]["expected"] = decoded_grid()
    (FIXTURES / "parity_cases.json").write_text(json.dumps(cases, indent=None, separators=(",", ":")) + "\n")
    print(f"wrote {FIXTURES / 'parity_cases.json'} and {GRID_STEM}.{{json,bin}}")


if __name__ == "__main__":
    main()
